const express = require('express');
const router = express.Router();
const controller = require('../controllers/contentController');
const { requireAuth, requireRole } = require('../middleware/auth');
router.get('/public', controller.listPublic);
router.get('/admin', requireAuth, requireRole('admin'), controller.listAdmin);
router.post('/homepage', requireAuth, requireRole('admin'), controller.saveHomepage);
router.put('/homepage/:id', requireAuth, requireRole('admin'), controller.saveHomepage);
router.delete('/homepage/:id', requireAuth, requireRole('admin'), controller.deleteHomepage);
router.post('/announcements', requireAuth, requireRole('admin'), controller.saveAnnouncement);
router.put('/announcements/:id', requireAuth, requireRole('admin'), controller.saveAnnouncement);
router.delete('/announcements/:id', requireAuth, requireRole('admin'), controller.deleteAnnouncement);
module.exports = router;
